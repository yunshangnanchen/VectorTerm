//! 全部配置项的元数据 —— 界面中间那一栏就是照这张表生成的。
//!
//! 每个 Field 对应 docs/config-manual.md 里的一个键:类型、默认值、取值范围、生效方式
//! (即时 / 新开标签 / 重启)和一句人话说明。要加新配置项,改这里就行,UI 不用动。
//!
//! 与 Python 版 settings/schema.py 一一对应,由它翻译而来。

/// 生效方式(手册第 18 章)
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Reload {
    Live,
    Tab,
    Restart,
}

impl Reload {
    pub fn label(&self) -> &'static str {
        match self {
            Reload::Live => "即时生效",
            Reload::Tab => "新开标签",
            Reload::Restart => "需重启",
        }
    }
}

/// 字段类型,决定中间栏用什么控件。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Bool,
    Int,
    Float,
    Str,
    Color,
    Path,
    Enum,
    List,
    Pair,
    Table,
    Code,
}

/// 一个配置项。
#[derive(Debug, Clone)]
pub struct Field {
    /// 点分路径,如 "tab_bar.colors.active_tab"
    pub path: &'static str,
    pub label: &'static str,
    pub kind: Kind,
    /// 默认值的 Lua 源码文本(用于"恢复默认"时写回)。
    pub default: Option<&'static str>,
    pub desc: &'static str,
    /// (值, 显示名)
    pub options: &'static [(&'static str, &'static str)],
    pub lo: Option<f64>,
    pub hi: Option<f64>,
    pub step: Option<f64>,
    pub unit: &'static str,
    /// list 的元素类型("str"/"path"/"color"/"enum")
    pub item: &'static str,
    /// list 的固定元素个数(0 = 不限)
    pub count: usize,
    /// pair 的子键
    pub sub: &'static [&'static str],
    pub sub_labels: &'static [&'static str],
    pub chapter: &'static str,
    pub reload: Reload,
    pub allow_none: bool,
    pub none_label: &'static str,
    pub hint: &'static str,
}

impl Field {
    pub fn parts(&self) -> Vec<&'static str> {
        self.path.split('.').collect()
    }

    /// 默认值解析成 Value(供"恢复默认"用)。预留:当前恢复默认走"删键"。
    #[allow(dead_code)]
    pub fn default_value(&self) -> Option<lua_default::Value> {
        self.default.map(|s| lua_default::parse_literal(s))
    }
}

/// 一个分组(界面上的一节)。
pub struct Group {
    pub key: &'static str,
    pub title: &'static str,
    pub desc: &'static str,
    pub chapter: &'static str,
    pub fields: &'static [Field],
}

// 用一个小模块避免和 store/lua 的 Value 混淆:默认值都是简单字面量。
mod lua_default {
    #[allow(dead_code)]
    pub enum Value {
        Str(String),
        Int(i64),
        Float(f64),
        Bool(bool),
        Nil,
        Auto, // 特殊值 "Auto"(未加引号,是标识符)
    }

    #[allow(dead_code)]
    pub fn parse_literal(s: &str) -> Value {
        match s {
            "true" => Value::Bool(true),
            "false" => Value::Bool(false),
            "nil" => Value::Nil,
            "Auto" | "auto" | "none" | "off" => Value::Auto,
            _ => {
                if s.starts_with('"') || s.starts_with('\'') {
                    Value::Str(s[1..s.len() - 1].to_owned())
                } else if let Ok(i) = s.parse::<i64>() {
                    Value::Int(i)
                } else if let Ok(f) = s.parse::<f64>() {
                    Value::Float(f)
                } else {
                    Value::Auto
                }
            }
        }
    }
}

